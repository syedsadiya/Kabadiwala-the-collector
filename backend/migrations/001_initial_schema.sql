CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('customer', 'collector', 'admin')),
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  phone TEXT,
  area TEXT,
  address TEXT,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  rating DOUBLE PRECISION NOT NULL DEFAULT 4,
  completed INTEGER NOT NULL DEFAULT 0,
  "totalWasteKg" DOUBLE PRECISION NOT NULL DEFAULT 0,
  categories JSONB NOT NULL DEFAULT '[]'::jsonb,
  "earningsToday" DOUBLE PRECISION NOT NULL DEFAULT 0,
  "earningsWeek" DOUBLE PRECISION NOT NULL DEFAULT 0,
  "earningsMonth" DOUBLE PRECISION NOT NULL DEFAULT 0,
  "earningsTotal" DOUBLE PRECISION NOT NULL DEFAULT 0,
  badges JSONB NOT NULL DEFAULT '[]'::jsonb,
  available BOOLEAN NOT NULL DEFAULT TRUE,
  "createdAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS centers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  area TEXT,
  incoming INTEGER NOT NULL DEFAULT 0,
  outgoing INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS recyclers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  location TEXT,
  accepts JSONB NOT NULL DEFAULT '[]'::jsonb,
  contact TEXT,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  capacity TEXT,
  status TEXT NOT NULL DEFAULT 'Pending verification',
  "createdAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS pickups (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer INTEGER NOT NULL REFERENCES users(id),
  collector INTEGER REFERENCES users(id),
  category TEXT NOT NULL,
  "qtyEst" DOUBLE PRECISION NOT NULL,
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  address TEXT,
  "pickupTime" TEXT,
  status TEXT NOT NULL DEFAULT 'REQUESTED',
  "createdAt" TIMESTAMPTZ NOT NULL,
  "pickupDate" TEXT,
  "preferredCollector" INTEGER REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS collections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "collectionCode" TEXT NOT NULL UNIQUE,
  pickup INTEGER NOT NULL REFERENCES pickups(id),
  collector INTEGER NOT NULL REFERENCES users(id),
  customer INTEGER NOT NULL REFERENCES users(id),
  category TEXT,
  weight DOUBLE PRECISION,
  quality TEXT,
  "amountPaid" DOUBLE PRECISION,
  "paymentMethod" TEXT,
  notes TEXT,
  center TEXT,
  recycler TEXT,
  status TEXT NOT NULL DEFAULT 'COLLECTED',
  co2 DOUBLE PRECISION,
  "createdAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS reward_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer INTEGER NOT NULL REFERENCES users(id),
  pickup INTEGER NOT NULL REFERENCES pickups(id),
  "collectionId" INTEGER NOT NULL UNIQUE REFERENCES collections(id),
  category TEXT NOT NULL,
  weight DOUBLE PRECISION NOT NULL CHECK (weight > 0),
  points INTEGER NOT NULL CHECK (points >= 0),
  "createdAt" TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS user_badges (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" INTEGER NOT NULL REFERENCES users(id),
  "badgeKey" TEXT NOT NULL,
  "earnedAt" TIMESTAMPTZ NOT NULL,
  UNIQUE ("userId", "badgeKey")
);

CREATE INDEX IF NOT EXISTS idx_pickups_status ON pickups(status);
CREATE INDEX IF NOT EXISTS idx_pickups_customer ON pickups(customer);
CREATE INDEX IF NOT EXISTS idx_collections_collector ON collections(collector);
CREATE INDEX IF NOT EXISTS idx_rewards_customer ON reward_transactions(customer);
CREATE INDEX IF NOT EXISTS idx_user_badges_user ON user_badges("userId");
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
